/** تجميع الجامعات حسب المنطقة الجغرافية في الجزائر بالاعتماد على اسم الولاية الوارد في اسم المؤسسة. */
export const REGIONS = ["الوسط", "الشرق", "الغرب", "الجنوب", "مؤسسات وطنية / عامة"] as const;
export type Region = (typeof REGIONS)[number];

const MAP: Record<Exclude<Region, "مؤسسات وطنية / عامة">, string[]> = {
  الوسط: ["الجزائر", "بومرداس", "البليدة", "تيبازة", "المدية", "البويرة", "تيزي وزو", "بجاية", "هواري بومدين", "بن عكنون", "الشلف", "عين الدفلى", "المسيلة"],
  الشرق: ["قسنطينة", "عنابة", "باتنة", "سطيف", "سكيكدة", "جيجل", "ميلة", "قالمة", "سوق أهراس", "تبسة", "أم البواقي", "خنشلة", "بسكرة", "برج بوعريريج", "الطارف", "باجي مختار"],
  الغرب: ["وهران", "تلمسان", "سيدي بلعباس", "مستغانم", "معسكر", "غليزان", "تيارت", "سعيدة", "عين تموشنت", "تيسمسيلت", "الطاهر مولاي", "مغنية"],
  الجنوب: ["ورقلة", "غرداية", "الأغواط", "أدرار", "تمنراست", "الوادي", "بشار", "إليزي", "تندوف", "النعامة", "البيض"],
};

export function regionOf(name: string): Region {
  // الجنوب أولاً لتفادي التداخل (الأغواط ... ) ثم بقية المناطق
  for (const r of ["الجنوب", "الغرب", "الشرق", "الوسط"] as const) {
    if (MAP[r].some((k) => name.includes(k))) return r;
  }
  return "مؤسسات وطنية / عامة";
}

export function groupByRegion(unis: string[]): { region: Region; items: string[] }[] {
  const g = new Map<Region, string[]>();
  for (const u of unis) {
    const r = regionOf(u);
    g.set(r, [...(g.get(r) ?? []), u]);
  }
  return REGIONS.filter((r) => g.has(r)).map((r) => ({ region: r, items: g.get(r)! }));
}
